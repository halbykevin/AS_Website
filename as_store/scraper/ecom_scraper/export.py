"""Export scraped products to JSON, CSV, Excel and/or a clean HTML catalog."""

from __future__ import annotations

import json
import os
import html
import datetime
from urllib.parse import urlparse

from .models import Product


def export(products: list[Product], out_dir: str, basename: str, formats: list[str]) -> list[str]:
    """Write the requested formats. Returns the list of files written."""
    os.makedirs(out_dir, exist_ok=True)
    written = []
    formats = [f.lower().lstrip(".") for f in formats]

    if "json" in formats:
        path = os.path.join(out_dir, f"{basename}.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump([p.to_dict() for p in products], fh, indent=2, ensure_ascii=False)
        written.append(path)

    if {"csv", "xlsx", "excel"} & set(formats):
        rows = [p.to_flat_dict() for p in products]
        import pandas as pd

        df = pd.DataFrame(rows)
        if "csv" in formats:
            path = os.path.join(out_dir, f"{basename}.csv")
            df.to_csv(path, index=False, encoding="utf-8-sig")  # BOM = Excel-friendly
            written.append(path)
        if {"xlsx", "excel"} & set(formats):
            path = os.path.join(out_dir, f"{basename}.xlsx")
            df.to_excel(path, index=False)
            written.append(path)

    if "html" in formats:
        path = os.path.join(out_dir, f"{basename}.html")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(_render_html(products))
        written.append(path)

    return written


