def _render_html(products: list[Product]) -> str:
    cards = "\n".join(_render_card(p) for p in products)
    shop, shop_url = _shop_identity(products)
    exported = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    return _HTML_TEMPLATE.format(
        count=len(products), cards=cards,
        shop=html.escape(shop), shop_url=html.escape(shop_url, quote=True),
        exported=html.escape(exported),
    )


def _shop_identity(products: list[Product]) -> tuple[str, str]:
    """Derive a shop name and homepage URL from the scraped product URLs."""
    for p in products:
        if p.url:
            parsed = urlparse(p.url)
            host = parsed.netloc.replace("www.", "")
            if host:
                return host, f"{parsed.scheme}://{parsed.netloc}/"
    return "Unknown source", "#"


def _render_card(p: Product) -> str:
    # Prefer a downloaded local file; otherwise use the remote image URL.
    img_src = p.image_files[0] if p.image_files else (p.images[0] if p.images else "")
    if img_src:
        thumb = f'<img src="{html.escape(img_src, quote=True)}" loading="lazy" alt="">'
    else:
        thumb = '<span class="no-img">no image</span>'

    name = html.escape(p.name or "Untitled")
    name_html = f'<a href="{html.escape(p.url, quote=True)}" target="_blank">{name}</a>' if p.url else name

    if p.price is not None:
        price = f"{p.price:,.2f}"
        if p.currency:
            price = f"{html.escape(p.currency)} {price}"
        price_html = f'<span class="price">{price}</span>'
    else:
        price_html = '<span class="price" style="color:#9aa5b1">—</span>'

    stock_html = ""
    if p.availability:
        out = "instock" not in p.availability.lower().replace(" ", "")
        stock_html = f'<span class="stock {"out" if out else ""}">{html.escape(p.availability)}</span>'

    brand_html = f'<div class="brand">{html.escape(p.brand)}</div>' if p.brand else ""
    search_blob = html.escape(" ".join(filter(None, [p.name, p.brand, p.sku])).lower(), quote=True)

    return f"""  <div class="card" data-search="{search_blob}">
    <div class="thumb">{thumb}</div>
    <div class="body">
      {brand_html}
      <div class="name">{name_html}</div>
      <div class="meta">{price_html}{stock_html}</div>
    </div>
  </div>"""
